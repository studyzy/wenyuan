// getMentalModel reads one mental model at the requested detail level. An
// unknown model is a normal negative answer naming the bank it was looked up
// in, as the reference reports it.
func (s *Server) getMentalModel(ctx context.Context, args map[string]any) (any, error) {
	bankID := s.bankArgument(ctx, args)
	modelID := stringArgument(args, "mental_model_id")
	if modelID == "" {
		return nil, invalidArgument("get_mental_model requires mental_model_id")
	}
	model, err := s.store.GetMentalModel(ctx, bankID, modelID)
	// An unknown bank reads as a missing model: the reference looks the model up
	// inside the bank, so it cannot tell the two apart and names only the model.
	if errors.Is(err, storage.ErrMentalModelNotFound) || errors.Is(err, storage.ErrBankNotFound) {
		return notFoundAnswer("Mental model '" + modelID + "' not found in bank '" + bankID + "'"), nil
	}
	if err != nil {
		return nil, err
	}
	detail := stringArgument(args, "detail")
	if detail == "" {
		detail = "full"
	}
	return mentalModelAtDetail(model, detail, s.store.IsStale(ctx, bankID, model), true), nil
}

func (s *Server) createMentalModel(ctx context.Context, args map[string]any) (any, error) {
	bankID := s.bankArgument(ctx, args)
	name := stringArgument(args, "name")
	if strings.TrimSpace(name) == "" {
		return nil, errors.New("name cannot be empty")
	}
	sourceQuery := stringArgument(args, "source_query")
	if strings.TrimSpace(sourceQuery) == "" {
		return nil, errors.New("source_query cannot be empty")
	}
	maxTokens := intArgument(args, "max_tokens", 2048)
	if maxTokens < 256 || maxTokens > 8192 {
		return nil, errors.New("max_tokens must be between 256 and 8192")
	}
	if message := validateTagsMatchArgument(args); message != "" {
		return nil, errors.New(message)
	}
	// The reference validates the supplied trigger before it writes anything: the
	// tool's argument model is checked by the framework's own validator, so a cron
	// expression its parser refuses, an unknown member or a member of the wrong
	// kind is a refused call rather than a value it stores and fails on later.
	trigger, err := validatedTriggerPatch(args)
	if err != nil {
		return nil, err
	}
	id := stringArgument(args, "mental_model_id")
	if id == "" {
		id = newID()
	}
	model, err := s.store.PutMentalModel(ctx, storage.MentalModel{
		ID:          id,
		BankID:      bankID,
		Subtype:     storage.SubtypePinned,
		Name:        name,
		SourceQuery: sourceQuery,
		Tags:        stringListArgument(args, "tags"),
		MaxTokens:   maxTokens,
		Trigger:     trigger,
	})
	if err != nil {
		return nil, err
	}
	// The content is generated by the refresh this queues, so the
	// acknowledgement names the operation the caller polls.
	operationID, err := s.enqueueMentalModelRefresh(ctx, bankID, model.ID, model.Name)
	if err != nil {
		return nil, err
	}
	return compactToolText(createMentalModelAck{
		MentalModelID: model.ID, OperationID: operationID, Status: "created",
		Message: "Mental model '" + name + "' created. Content is being generated asynchronously.",
	}), nil
}

// enqueueMentalModelRefresh queues a refresh of one mental model and returns the
// operation identifier, recording the model's identifier and name in the
// operation's result metadata the way the HTTP route does.
func (s *Server) enqueueMentalModelRefresh(ctx context.Context, bankID, modelID, name string) (string, error) {
	result, err := s.store.EnqueueOperation(ctx, storage.EnqueueRequest{
		Operation: storage.Operation{
			BankID:           bankID,
			OperationType:    storage.OperationTypeRefreshMentalModel,
			Payload:          map[string]any{storage.MentalModelIDPayloadKey: modelID},
			ResultMetadata:   map[string]any{storage.MentalModelIDPayloadKey: modelID, "name": name},
			SerializationKey: storage.MentalModelSerializationKey(modelID),
		},
		DedupeByPayloadKey: storage.MentalModelIDPayloadKey,
	})
	if err != nil {
		return "", err
	}
	return result.Operation.OperationID, nil
}

func (s *Server) updateMentalModel(ctx context.Context, args map[string]any) (any, error) {
	bankID := s.bankArgument(ctx, args)
	modelID := stringArgument(args, "mental_model_id")
	if modelID == "" {
		return nil, invalidArgument("update_mental_model requires mental_model_id")
	}
	patch := storage.MentalModelPatch{}
	if name := stringArgument(args, "name"); name != "" {
		patch.Name = &name
	}
	if sourceQuery := stringArgument(args, "source_query"); sourceQuery != "" {
		patch.SourceQuery = &sourceQuery
	}
	if tags := stringListArgument(args, "tags"); tags != nil {
		patch.Tags = &tags
	}
	if _, ok := args["max_tokens"]; ok {
		maxTokens := intArgument(args, "max_tokens", 0)
		if maxTokens < 256 || maxTokens > 8192 {
			return nil, errors.New("max_tokens must be between 256 and 8192")
		}
		patch.MaxTokens = &maxTokens
	}
	if message := validateTagsMatchArgument(args); message != "" {
		return nil, errors.New(message)
	}
	// Only what the caller supplied is validated: the reference's tool checks the
	// trigger model it was handed (`mcp_tools.py::_mental_model_trigger_patch`),
	// whose one cross-member rule is that a *single* supplied object may not state
	// both schedules. The engine then merges the patch over the model's current
	// trigger and pops the schedule the patch superseded
	// (`memory_engine.py:19994-20002`), so the merged result cannot express a
	// conflict and gets no further check.
	supplied, err := validatedTriggerPatch(args)
	if err != nil {
		return nil, err
	}
	if supplied != nil {
		current, err := s.store.GetMentalModel(ctx, bankID, modelID)
		if errors.Is(err, storage.ErrMentalModelNotFound) {
			return notFoundAnswer("Mental model '" + modelID + "' not found in bank '" + bankID + "'"), nil
		}
		if err != nil {
			return nil, err
		}
		merged := mergeTriggerPatch(supplied, current.Trigger)
		patch.Trigger = &merged
	}
	model, err := s.store.UpdateMentalModel(ctx, bankID, modelID, patch)
	if errors.Is(err, storage.ErrMentalModelNotFound) {
		return notFoundAnswer("Mental model '" + modelID + "' not found in bank '" + bankID + "'"), nil
	}
	if err != nil {
		return nil, err
	}
	// The update reports the model at full detail, without the staleness verdict
	// the single-model read computes.
	return mentalModelAtDetail(model, "full", false, false), nil
}

func (s *Server) deleteMentalModel(ctx context.Context, args map[string]any) (any, error) {
	bankID := s.bankArgument(ctx, args)
	modelID := stringArgument(args, "mental_model_id")
	if modelID == "" {
		return nil, invalidArgument("delete_mental_model requires mental_model_id")
	}
	if err := s.store.DeleteMentalModel(ctx, bankID, modelID); err != nil {
		if errors.Is(err, storage.ErrMentalModelNotFound) {
			return notFoundAnswer("Mental model '" + modelID + "' not found in bank '" + bankID + "'"), nil
		}
		return nil, err
	}
	return compactToolText(deleteMentalModelAck{Status: "deleted", MentalModelID: modelID}), nil
}

func (s *Server) refreshMentalModel(ctx context.Context, args map[string]any) (any, error) {
	bankID := s.bankArgument(ctx, args)
	modelID := stringArgument(args, "mental_model_id")
	if modelID == "" {
		return nil, invalidArgument("refresh_mental_model requires mental_model_id")
	}
	// The model is read first: its name goes into the operation's result
	// metadata, which is what the operation-status read reports back, and a
	// model that is not in the bank is an answer rather than a queued row.
	model, err := s.store.GetMentalModel(ctx, bankID, modelID)
	if errors.Is(err, storage.ErrMentalModelNotFound) || errors.Is(err, storage.ErrBankNotFound) {
		return notFoundAnswer("Mental model " + modelID + " not found in bank " + bankID), nil
	}
	if err != nil {
		return nil, err
	}
	operationID, err := s.enqueueMentalModelRefresh(ctx, bankID, modelID, model.Name)
	if err != nil {
		return nil, err
	}
	return compactToolText(refreshMentalModelAck{
		OperationID: operationID, Status: "queued",
		Message: "Refresh queued for mental model '" + modelID + "'.",
	}), nil
}

