// listDocuments lists a bank's documents with the same rows and page envelope
// the HTTP listing serves.
func (s *Server) listDocuments(ctx context.Context, args map[string]any) (any, error) {
	bankID := s.bankArgument(ctx, args)
	if s.bankMissing(ctx, bankID) {
		return bankMissingAnswer(bankID), nil
	}
	limit, offset := intArgument(args, "limit", 100), intArgument(args, "offset", 0)
	page, err := s.store.ListDocuments(ctx, storage.DocumentQuery{
		BankID: bankID,
		Query:  stringArgument(args, "q"),
		Limit:  limit,
		Offset: offset,
	})
	if err != nil {
		return nil, err
	}
	items := make([]documentListItem, 0, len(page.Documents))
	for _, doc := range page.Documents {
		item := toDocumentListItem(doc)
		item.MatchedFields = doc.MatchedFields
		if item.MatchedFields == nil {
			item.MatchedFields = []string{}
		}
		items = append(items, item)
	}
	return documentListPage{
		Items: items, Total: page.Total, Limit: limit, Offset: offset,
		TotalIsEstimate: page.TotalIsEstimate,
	}, nil
}

// getDocument reads one document. An unknown document is a normal negative
// answer, as it is in the reference.
func (s *Server) getDocument(ctx context.Context, args map[string]any) (any, error) {
	bankID := s.bankArgument(ctx, args)
	docID := stringArgument(args, "document_id")
	if docID == "" {
		return nil, invalidArgument("get_document requires document_id")
	}
	doc, err := s.store.GetDocument(ctx, bankID, docID)
	if errors.Is(err, storage.ErrDocumentNotFound) {
		return notFoundAnswer("Document '" + docID + "' not found"), nil
	}
	if err != nil {
		return nil, err
	}
	detail, err := s.documentDetailPayload(ctx, bankID, doc)
	if err != nil {
		return nil, err
	}
	return detail, nil
}

func (s *Server) deleteDocument(ctx context.Context, args map[string]any) (any, error) {
	bankID := s.bankArgument(ctx, args)
	docID := stringArgument(args, "document_id")
	if docID == "" {
		return nil, invalidArgument("delete_document requires document_id")
	}
	removed, err := s.store.DeleteDocument(ctx, bankID, docID)
	if err != nil && !errors.Is(err, storage.ErrDocumentNotFound) {
		return nil, err
	}
	// A document that was not there is not a failure: the reference reports the
	// deletion with a zero count.
	deleted := 0
	if err == nil {
		deleted = 1
	}
	return compactToolText(deleteDocumentAck{
		Status: "deleted", DocumentID: docID,
		DocumentDeleted: deleted, MemoryUnitsDeleted: removed,
	}), nil
}

// listOperations lists a bank's async operations as the engine reports them:
// the rows and the total, without the bank identity and page bounds the HTTP
// listing adds.
func (s *Server) listOperations(ctx context.Context, args map[string]any) (any, error) {
	bankID := s.bankArgument(ctx, args)
	if s.bankMissing(ctx, bankID) {
		return bankMissingAnswer(bankID), nil
	}
	page, err := s.store.ListOperations(ctx, storage.OperationQuery{
		BankID:         bankID,
		Status:         stringArgument(args, "status"),
		Type:           stringArgument(args, "type"),
		Limit:          intArgument(args, "limit", 20),
		Offset:         intArgument(args, "offset", 0),
		ExcludeParents: boolArgument(args, "exclude_parents", false),
	})
	if err != nil {
		return nil, err
	}
	operations := make([]memoryops.Operation, 0, len(page.Operations))
	for _, op := range page.Operations {
		operations = append(operations, memoryops.ToOperationListDTO(op))
	}
	return operationListPage{Total: page.Total, Operations: operations}, nil
}

// getOperation reads one async operation. An unknown identifier is a normal
// result carrying status not_found, exactly as the reference reports it.
func (s *Server) getOperation(ctx context.Context, args map[string]any) (any, error) {
	bankID := s.bankArgument(ctx, args)
	opID := stringArgument(args, "operation_id")
	if opID == "" {
		return nil, invalidArgument("get_operation requires operation_id")
	}
	op, err := s.store.GetOperation(ctx, bankID, opID)
	if errors.Is(err, storage.ErrOperationNotFound) {
		return operationNotFound{
			OperationID: opID, Status: string(storage.StatusNotFound), ID: opID,
		}, nil
	}
	if err != nil {
		return nil, err
	}
	var children []storage.ChildOperation
	if op.IsParent {
		children, err = s.store.GetOperationChildren(ctx, bankID, opID)
		if err != nil {
			return nil, err
		}
	}
	return operationDetailPayload(op, opID, children), nil
}

