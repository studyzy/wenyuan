// credentialConfigFields and staticConfigFields are the two sets parsed once
// from the name lists above.
var credentialConfigFields = fieldNameSet(credentialConfigFieldNames)
var staticConfigFields = fieldNameSet(staticConfigFieldNames)

func fieldNameSet(names string) map[string]struct{} {
	set := map[string]struct{}{}
	for _, name := range strings.Fields(names) {
		set[name] = struct{}{}
	}
	return set
}
