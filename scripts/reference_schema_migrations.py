"""Generate the migration series from the reference database.

The PostgreSQL schema this project serves is the reference database's schema, so
the migration series is not hand-written: it is emitted from the reference's own
catalogue, object by object, using the same rendering functions a client sees.
That is what makes the built schema identical to the reference rather than
merely similar.

Why the catalogue and not `pg_dump` output: a dump is text a parser re-reads, and
PostgreSQL does not always store back what it was given. Replaying the reference
dump produces `memory_units_bank_id_not_null1` where the reference says
`memory_units_bank_id_not_null`, and rewrites a check constraint's array cast
into a per-element cast. Emitting `pg_get_constraintdef` / `pg_get_indexdef` /
`pg_get_functiondef` and `format_type` verbatim cannot drift that way, because
those are the definitions the schema reports.

Output: migrations/ and internal/storage/embedded/ (the embedded copy the binary
actually reads), as a short numbered series:

    0001_extensions             the extensions the reference's objects need
    0002_reference_tables       CREATE TABLE, columns, defaults, identity keys
    0003_reference_constraints  primary keys, uniques, checks and foreign keys
    0004_reference_indexes      every index that is not backing a constraint
    0005_reference_functions    the maintenance discovery routines

Usage:

    python3 scripts/reference_schema_migrations.py
    # override the source database with WENYUAN_REFERENCE_URL
"""

import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIRS = [os.path.join(ROOT, "migrations"),
        os.path.join(ROOT, "internal", "storage", "embedded")]

SOURCE = os.environ.get(
    "WENYUAN_REFERENCE_URL",
    "postgresql://hindsight:hindsight@127.0.0.1:5432/hindsight")
SCHEMA = os.environ.get("WENYUAN_REFERENCE_SCHEMA", "public")

# Alembic's bookkeeping and this project's own are not the schema.
SKIPPED_TABLES = {"alembic_version", "schema_migrations"}

EXTENSIONS = """\
-- 0001_extensions
--
-- The extensions the reference's objects depend on. The reference database had
-- them installed before its tables existed, so its own dump does not carry
-- them; a schema built from this series has to install them itself, before the
-- objects that need them.
--
-- The creations run under an advisory lock. CREATE EXTENSION IF NOT EXISTS is
-- not safe under concurrency: two sessions both pass the existence check, both
-- attempt the create, and one fails on the catalogue's unique index on the
-- extension name. A migration runs from every process that starts, so two
-- deployments coming up together would collide. The lock serializes them and is
-- released when the transaction ends.

SELECT pg_advisory_xact_lock(hashtext('wenyuan:extensions'));
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS btree_gin;
"""

HEADERS = {
    "reference_tables": """\
-- 0002_reference_tables
--
-- Every table of the reference schema: its columns in their declared order,
-- with the declared type, default, collation, identity or generation
-- expression, and the name of each NOT NULL constraint.
--
-- Generated by scripts/reference_schema_migrations.py from the reference
-- database catalogue. Do not hand-edit; regenerate instead.
""",
    "reference_constraints": """\
-- 0003_reference_constraints
--
-- The reference's primary keys, uniques and checks, then its foreign keys.
-- Order matters: a foreign key can only be added once the unique constraint it
-- points at exists.
--
-- Generated by scripts/reference_schema_migrations.py. Do not hand-edit.
""",
    "reference_indexes": """\
-- 0004_reference_indexes
--
-- Every index of the reference that is not backing a constraint.
--
-- Generated by scripts/reference_schema_migrations.py. Do not hand-edit.
""",
    "reference_functions": """\
-- 0005_reference_functions
--
-- The reference's maintenance discovery routines. Each is a single round-trip
-- that scans every schema for the work that is due; the body is the behaviour,
-- so it is reproduced rather than reimplemented.
--
-- Generated by scripts/reference_schema_migrations.py. Do not hand-edit.
""",
}

ORDER = ["extensions", "reference_tables", "reference_constraints",
         "reference_indexes", "reference_functions"]


def query(sql):
    """Run one query and return its rows, tab-separated."""
    result = subprocess.run(
        ["psql", SOURCE, "-X", "-A", "-t", "-F", "\t", "-R", "\x1e",
         "-v", "ON_ERROR_STOP=1", "-c", sql],
        capture_output=True, text=True)
    if result.returncode != 0:
        raise SystemExit("psql failed:\n" + result.stderr + "\nfor:\n" + sql)
    # A record separator that is not a newline, because a function body is
    # multi-line text and its own line comments are part of the definition.
    return [row.split("\t") for row in result.stdout.split("\x1e") if row.strip()]


# A check constraint that compares a text column against an array of
# `character varying` literals is stored as an array-level coercion. Feeding the
# deparsed text back would coerce each element instead, which is equivalent but
# deparses differently, so the array is asked for as `character varying[]` and
# the parser rebuilds the same tree.
ARRAY_OF_TEXT = re.compile(r"\((ARRAY\[[^\]]*\])\)::text\[\]")


def render_check(text):
    return ARRAY_OF_TEXT.sub(r"(\1::character varying[])", text)


def unqualify(text):
    """Drop the source schema's qualification so the driver's search path wins."""
    return text.replace(SCHEMA + ".", "")


def tables():
    rows = query(f"""
        SELECT c.relname
        FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = '{SCHEMA}' AND c.relkind = 'r'
        ORDER BY c.relname
    """)
    return [r[0] for r in rows if r[0] not in SKIPPED_TABLES]


def create_table(name):
    columns = query(f"""
        SELECT a.attname,
               format_type(a.atttypid, a.atttypmod),
               CASE WHEN a.attcollation <> t.typcollation
                    THEN (SELECT collname FROM pg_collation WHERE oid = a.attcollation)
                    ELSE '' END,
               a.attnotnull::text,
               COALESCE(pg_get_expr(d.adbin, d.adrelid), ''),
               a.attidentity,
               a.attgenerated,
               COALESCE((SELECT con.conname FROM pg_constraint con
                         WHERE con.conrelid = a.attrelid AND con.contype = 'n'
                           AND con.conkey = ARRAY[a.attnum]::smallint[]), '')
        FROM pg_attribute a
        JOIN pg_type t ON t.oid = a.atttypid
        LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attrelid = '{SCHEMA}.{name}'::regclass
          AND a.attnum > 0 AND NOT a.attisdropped
        ORDER BY a.attnum
    """)
    lines = []
    for column, ctype, collation, notnull, default, identity, generated, notnull_name in columns:
        piece = f"    {column} {unqualify(ctype)}"
        if collation:
            piece += f" COLLATE {collation}"
        if generated == "s":
            piece += f" GENERATED ALWAYS AS ({unqualify(default)}) STORED"
        elif identity == "d":
            piece += " GENERATED BY DEFAULT AS IDENTITY"
        elif identity == "a":
            piece += " GENERATED ALWAYS AS IDENTITY"
        elif default:
            piece += f" DEFAULT {unqualify(default)}"
        if notnull == "true":
            piece += (f" CONSTRAINT {notnull_name} NOT NULL"
                      if notnull_name else " NOT NULL")
        lines.append(piece)
    return "CREATE TABLE %s (\n%s\n);" % (name, ",\n".join(lines))


def constraints(name):
    rows = query(f"""
        SELECT con.conname, con.contype::text, pg_get_constraintdef(con.oid)
        FROM pg_constraint con
        WHERE con.conrelid = '{SCHEMA}.{name}'::regclass
          AND con.contype IN ('p', 'u', 'c')
        ORDER BY con.conname
    """)
    return ["ALTER TABLE %s ADD CONSTRAINT %s %s;" %
            (name, row[0], unqualify(render_check(row[2]) if row[1] == "c" else row[2]))
            for row in rows]


def foreign_keys(name):
    rows = query(f"""
        SELECT con.conname, pg_get_constraintdef(con.oid)
        FROM pg_constraint con
        WHERE con.conrelid = '{SCHEMA}.{name}'::regclass AND con.contype = 'f'
        ORDER BY con.conname
    """)
    return ["ALTER TABLE %s ADD CONSTRAINT %s %s;" %
            (name, row[0], unqualify(row[1])) for row in rows]


def indexes(name):
    rows = query(f"""
        SELECT pg_get_indexdef(i.indexrelid)
        FROM pg_index i
        JOIN pg_class c ON c.oid = i.indexrelid
        WHERE i.indrelid = '{SCHEMA}.{name}'::regclass
          AND NOT i.indisprimary
          AND NOT EXISTS (SELECT 1 FROM pg_constraint con WHERE con.conindid = i.indexrelid)
        ORDER BY c.relname
    """)
    return [unqualify(r[0]) + ";" for r in rows]


def functions():
    rows = query(f"""
        SELECT pg_get_functiondef(p.oid)
        FROM pg_proc p
        JOIN pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname = '{SCHEMA}' AND p.prokind IN ('f', 'p')
          AND NOT EXISTS (
              SELECT 1 FROM pg_depend d
              WHERE d.objid = p.oid AND d.deptype = 'e')
        ORDER BY p.proname, pg_get_function_identity_arguments(p.oid)
    """)
    return [unqualify(r[0]).rstrip(";") + ";" for r in rows]


def build():
    names = tables()
    files = {"extensions": EXTENSIONS}
    files["reference_tables"] = "\n\n".join([create_table(t) for t in names]) + "\n"
    files["reference_constraints"] = "\n\n".join(
        [s for t in names for s in constraints(t)] +
        [s for t in names for s in foreign_keys(t)]) + "\n"
    files["reference_indexes"] = "\n\n".join(
        [s for t in names for s in indexes(t)]) + "\n"
    files["reference_functions"] = "\n\n".join(functions()) + "\n"

    bodies = {}
    for index, key in enumerate(ORDER, start=1):
        bodies[index] = files[key] if key == "extensions" else HEADERS[key] + "\n" + files[key]

    for directory in DIRS:
        for stale in os.listdir(directory):
            if stale.endswith(".sql"):
                os.remove(os.path.join(directory, stale))
        for index, key in enumerate(ORDER, start=1):
            path = os.path.join(directory, "%04d_%s.sql" % (index, key))
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(bodies[index])

    for index, key in enumerate(ORDER, start=1):
        text = bodies[index]
        print("%04d_%s.sql  %d lines" % (index, key, text.count("\n")))


if __name__ == "__main__":
    build()