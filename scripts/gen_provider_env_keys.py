#!/usr/bin/env python3
"""Regenerate internal/config/provider_env_keys.go.

The provider families (chat LLM, the scoped LLM roles, embeddings, reranker and
the global litellm credentials) are a frozen operator-facing contract: an
operator's environment file must be accepted key by key. The list of names is
therefore enumerated rather than guessed, and this script re-derives it from the
contract document so a newly added key shows up as a diff instead of being
silently missing.

Usage: gen_provider_env_keys.py <path-to-contract-config.py> [out.go]

The contract document is the module that declares the ``ENV_*`` string
constants; the script only reads declarations whose value contains one of the
family markers below.

The reference document spells its keys with the reference's prefix and this
service spells the same keys with its own: SOURCE_PREFIX is what the document
is read with, TARGET_PREFIX is what is emitted, and the rename between them is
exactly the prefix — the key body is the contract and never changes.
"""

import re
import sys

# The prefix the reference document declares its keys with, and the prefix
# this service spells them with. The contract is the key body; only the
# namespace belongs to whoever serves it.
SOURCE_PREFIX = "HINDSIGHT_API_"
TARGET_PREFIX = "WENYUAN_API_"

# Family markers, as they appear in the key name itself. Order matters: the
# first matching marker wins, and the scoped roles are tested before the bare
# "LLM" marker.
FAMILIES = [
    ("retain_llm", (SOURCE_PREFIX + "RETAIN_LLM_",)),
    ("reflect_llm", (SOURCE_PREFIX + "REFLECT_LLM_",)),
    ("consolidation_llm", (SOURCE_PREFIX + "CONSOLIDATION_LLM_",)),
    ("mental_model_refresh_llm", (SOURCE_PREFIX + "MENTAL_MODEL_REFRESH_LLM_",)),
    ("embeddings", (SOURCE_PREFIX + "EMBEDDING_", SOURCE_PREFIX + "EMBEDDINGS_")),
    ("reranker", (SOURCE_PREFIX + "RERANKER_",)),
    ("litellm", (SOURCE_PREFIX + "LITELLM_",)),
    ("llm", (SOURCE_PREFIX + "LLM_", SOURCE_PREFIX + "SKIP_LLM_VERIFICATION")),
]

# Keys owned by another family group; excluded here so the families do not
# overlap.
EXCLUDED = (SOURCE_PREFIX + "ENABLE_BANK_LLM_HEALTH",)

# Tokens that keep their conventional spelling when name-mangling a key.
TOKEN_CASE = {
    "LLM": "LLM",
    "API": "API",
    "URL": "URL",
    "ID": "ID",
    "MPS": "MPS",
    "CPU": "CPU",
    "FP16": "FP16",
    "IPV4": "IPv4",
    "SDK": "SDK",
    "4XX": "4XX",
    "GPU": "GPU",
}


def const_name(key: str) -> str:
    body = key[len(TARGET_PREFIX):]
    parts = []
    for token in body.split("_"):
        parts.append(TOKEN_CASE.get(token, token.capitalize()))
    return "Env" + "".join(parts)


def target_key(key: str) -> str:
    """The key as this service spells it: same body, our own namespace."""
    return TARGET_PREFIX + key[len(SOURCE_PREFIX):]


def family_of(key: str):
    for family, markers in FAMILIES:
        for marker in markers:
            if key.startswith(marker):
                return family
    return None


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    source = open(sys.argv[1], encoding="utf-8").read()
    out_path = sys.argv[2] if len(sys.argv) > 2 else "internal/config/provider_env_keys.go"

    declared = re.findall(r'^\s*(\w+)\s*=\s*"([^"]+)"', source, re.M)
    families: dict[str, list[str]] = {name: [] for name, _ in FAMILIES}
    seen: set[str] = set()
    for _, value in declared:
        if not value.startswith(SOURCE_PREFIX):
            continue
        if value in EXCLUDED:
            continue
        family = family_of(value)
        if family is None or value in seen:
            continue
        seen.add(value)
        families[family].append(target_key(value))

    # Existing constants already declared in the package, so generated names
    # never collide with a hand-written one.
    existing: dict[str, str] = {}
    import glob

    for path in glob.glob("internal/config/*.go"):
        if path.endswith("provider_env_keys.go"):
            continue
        for text in open(path, encoding="utf-8"):
            m = re.search(r'^\s*(Env\w+)\s*=\s*"([^"]+)"', text)
            if m:
                existing[m.group(2)] = m.group(1)
    existing_names = set(existing.values())

    lines = [
        "// Code generated by scripts/gen_provider_env_keys.py. DO NOT EDIT.",
        "",
        "package config",
        "",
        "// Provider-family environment keys. Every key an operator's environment",
        "// file may carry in these families is enumerated so resolution and",
        "// refusal are decided by name rather than by accident.",
        "const (",
    ]
    generated: dict[str, str] = {}
    for family, _ in FAMILIES:
        for key in families[family]:
            if key in existing:
                continue
            name = const_name(key)
            while name in existing_names or name in generated:
                name += "_"
            generated[key] = name
            existing_names.add(name)
            lines.append(f'\t{name} = "{key}"')
    lines.append(")")
    lines.append("")
    lines.append("// providerFamilyKeys enumerates the family members in name order.")
    lines.append("var providerFamilyKeys = map[string][]string{")
    for family, _ in FAMILIES:
        lines.append(f'\t"{family}": {{')
        for key in sorted(families[family]):
            lines.append(f'\t\t"{key}",')
        lines.append("\t},")
    lines.append("}")
    lines.append("")

    open(out_path, "w", encoding="utf-8").write("\n".join(lines))
    # Keep the checked-in file gofmt-clean so re-running the generator produces
    # no spurious diff.
    import shutil
    import subprocess

    gofmt = shutil.which("gofmt")
    if gofmt:
        subprocess.run([gofmt, "-w", out_path], check=False)
    total = sum(len(v) for v in families.values())
    print(f"wrote {out_path}: {total} keys, {len(generated)} new constants")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())