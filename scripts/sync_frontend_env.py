#!/usr/bin/env python3
"""Generate the frontend's environment from the backend's configuration.

The console has no credentials of its own: it signs in with — and proxies with —
the keys the backend already has. This reads the backend configuration
(etc/wenyuan.yaml, or WENYUAN_API_CONFIG_FILE) and renders the
WENYUAN_CP_* lines the frontend unit needs, so a deployment configures a key
once, in one file.

Keys are spelled as the backend spells them: a group flattens onto its prefix
(`admin: {api_key: x}` and `admin_api_key: x` both answer `admin_api_key`).

    python3 scripts/sync_frontend_env.py                     # print
    python3 scripts/sync_frontend_env.py --output /path      # write, mode 600
"""

import argparse
import os
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_CONFIG = ROOT / "etc" / "wenyuan.yaml"
DEFAULT_PORT = "18888"

HEADER = """\
# Environment for wenyuan-frontend.service.
#
# GENERATED by `make service-env` from the backend configuration
# (etc/wenyuan.yaml). Edit the backend file, not this one: the console has no
# keys of its own, it signs in with — and proxies with — the backend's.
#
#   WENYUAN_CP_DATAPLANE_*  where the BFF finds the API, and the data key it
#                           presents (the backend's tenant_api_key, used only in
#                           single-tenant mode; tenants use their own wyk_ keys).
#   WENYUAN_CP_ADMIN_*      the management plane and its operator key. Without
#                           it the console cannot manage tenants, and the
#                           operator session cannot be opened.
"""


def flatten(data, prefix=""):
    """Flatten nested mappings onto an underscore-joined key, as the backend does."""
    out = {}
    for key, value in data.items():
        name = f"{prefix}{key}"
        if isinstance(value, dict):
            out.update(flatten(value, f"{name}_"))
        elif value is not None:
            out[name] = value
    return out


def render(flat):
    port = str(flat.get("port", DEFAULT_PORT)).strip() or DEFAULT_PORT
    data_key = str(flat.get("tenant_api_key", "")).strip()
    admin_listen = str(flat.get("admin_listen", "")).strip()
    admin_key = str(flat.get("admin_api_key", "")).strip()

    lines = [
        HEADER,
        f"WENYUAN_CP_DATAPLANE_API_URL=http://127.0.0.1:{port}",
        f"WENYUAN_CP_DATAPLANE_API_KEY={data_key}",
    ]
    if admin_listen:
        lines.append(f"WENYUAN_CP_ADMIN_API_URL=http://{admin_listen}")
        lines.append(f"WENYUAN_CP_ADMIN_API_KEY={admin_key}")
    else:
        lines.append("# No admin_listen in the backend configuration: tenant management is off.")
    return "\n".join(lines) + "\n"


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=os.environ.get("WENYUAN_API_CONFIG_FILE", str(DEFAULT_CONFIG)),
                        help="backend configuration file (default: etc/wenyuan.yaml)")
    parser.add_argument("--output", help="write here with mode 600 instead of printing")
    args = parser.parse_args(argv)

    path = pathlib.Path(args.config)
    try:
        document = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except FileNotFoundError:
        print(f"configuration file not found: {path}", file=sys.stderr)
        return 1
    except yaml.YAMLError as error:
        print(f"configuration file is not valid YAML: {error}", file=sys.stderr)
        return 1
    if not isinstance(document, dict):
        print(f"configuration file is not a mapping: {path}", file=sys.stderr)
        return 1

    rendered = render(flatten(document))
    if args.output:
        target = pathlib.Path(args.output)
        target.write_text(rendered, encoding="utf-8")
        target.chmod(0o600)
    else:
        sys.stdout.write(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
