"""Render the schema alignment inventory from the two rendered inventories.

Reads the two files `scripts/schema_diff.sql` wrote (`/tmp/up.schema` for the
upstream database, `/tmp/wy.schema` for a freshly migrated wenyuan schema) and
writes `docs/SCHEMA-ALIGNMENT.md`.

Objects are compared **in full**, not by name. An index with the upstream name
and a different column list, or a column with the upstream name and a different
type, is a difference a name-only comparison hides — so every row is matched on
the fields that identify the object and then compared on the rest, and anything
that differs lands in a `Definitions that differ` section.

Run after rendering both sides. Give each side its own DATABASE and render the
public schema: the upstream migrations build the public schema of a dedicated
database (vchord's create_hypertable in the search extension refuses a
non-public one), so a throwaway schema in the same database is not a comparable
wenyuan side.

    psql -d <upstream> -v schema=public -f scripts/schema_diff.sql > /tmp/up.schema
    psql -d <wenyuan>  -v schema=public -f scripts/schema_diff.sql > /tmp/wy.schema
    python3 scripts/schema_inventory.py
"""

# How many fields after the kind identify an object of that kind. Everything
# from there on is the definition that has to match.
IDENTITY = {
    "TABLE": 1,
    "COLUMN": 2,
    "INDEX": 2,
    "CONSTRAINT": 2,
    "FUNCTION": 2,
    "VIEW": 1,
    "SEQUENCE": 1,
    "TRIGGER": 2,
    "EXTENSION": 1,
}

HEADINGS = {
    "TABLE": "Tables",
    "COLUMN": "Columns",
    "INDEX": "Indexes",
    "CONSTRAINT": "Constraints",
    "FUNCTION": "Functions",
    "VIEW": "Views",
    "SEQUENCE": "Sequences",
    "TRIGGER": "Triggers",
    "EXTENSION": "Extensions",
}

ORDER = ["TABLE", "COLUMN", "INDEX", "CONSTRAINT", "FUNCTION", "VIEW",
         "SEQUENCE", "TRIGGER", "EXTENSION"]


def load(path):
    """Return {kind: {(identity fields): full row}} for one rendered schema."""
    objects = {}
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if not line or "|" not in line:
            continue
        parts = line.split("|")
        kind = parts[0]
        if kind not in IDENTITY:
            continue
        objects.setdefault(kind, {})[tuple(parts[1:1 + IDENTITY[kind]])] = line
    return objects


def compare(up, wy):
    """Return (missing, extra, differing) as sorted lists of rows for one kind."""
    missing = sorted(up[k] for k in up.keys() - wy.keys())
    extra = sorted(wy[k] for k in wy.keys() - up.keys())
    differing = sorted(
        (up[k], wy[k]) for k in up.keys() & wy.keys() if up[k] != wy[k]
    )
    return missing, extra, differing


def row(line):
    """Drop the leading kind field, which the section heading already names."""
    return "|".join(line.split("|")[1:])


def section(title, rows, fmt):
    out = [f"### {title} ({len(rows)})", ""]
    if not rows:
        out.append("None.")
        out.append("")
        return out
    out.append("```")
    for r in rows:
        out.append(fmt(r))
    out.append("```")
    out.append("")
    return out


def main():
    up = load("/tmp/up.schema")
    wy = load("/tmp/wy.schema")

    results = {}
    for kind in ORDER:
        results[kind] = compare(up.get(kind, {}), wy.get(kind, {}))

    missing_totals = {k: len(results[k][0]) for k in ORDER}
    extra_totals = {k: len(results[k][1]) for k in ORDER}
    differing_totals = {k: len(results[k][2]) for k in ORDER}

    lines = [
        "# Schema alignment inventory",
        "",
        "Generated by `scripts/schema_inventory.py` from two live schemas rendered by",
        "`scripts/schema_diff.sql`: the upstream database (`hindsight`, built by",
        "Alembic) and a freshly migrated wenyuan schema.",
        "",
        "**This is the work order.** It is derived from `pg_catalog`, never from",
        "reading migrations or documentation, because the question is what a query",
        "sees at run time.",
        "",
        "Objects are matched on their identity and then compared **whole**, so a",
        "column with the upstream name and a different type, an index with the",
        "upstream name and a different column list, or a function with the upstream",
        "name and a different body each land in a section below.",
        "",
        "## Totals",
        "",
        "| kind | upstream | wenyuan | missing | extra | differs |",
        "|---|---|---|---|---|---|",
    ]
    for kind in ORDER:
        lines.append(
            f"| {HEADINGS[kind].lower()} | {len(up.get(kind, {}))} | {len(wy.get(kind, {}))} "
            f"| {missing_totals[kind]} | {extra_totals[kind]} | {differing_totals[kind]} |"
        )
    lines += [
        "",
        "A missing entry breaks a query or loses a guarantee. A differing entry",
        "means the object exists on both sides but is not the same object. An extra",
        "entry is additive unless it collides with an upstream name or imposes a",
        "guarantee upstream does not, in which case it can reject a valid upstream",
        "write.",
        "",
    ]

    for kind in ORDER:
        heading = HEADINGS[kind]
        missing, extra, differing = results[kind]
        lines += section(f"{heading} upstream has and wenyuan lacks", missing, row)
        lines += section(f"{heading} wenyuan has and upstream lacks", extra, row)
        if differing:
            body = []
            for up_row, wy_row in differing:
                body.append("upstream: " + row(up_row))
                body.append("wenyuan:  " + row(wy_row))
                body.append("")
            lines.append(f"### {heading} that differ ({len(differing)})")
            lines.append("")
            lines.append("```")
            lines.extend(body[:-1])
            lines.append("```")
            lines.append("")

    with open("docs/SCHEMA-ALIGNMENT.md", "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print("wrote docs/SCHEMA-ALIGNMENT.md")
    for kind in ORDER:
        print(f"  {HEADINGS[kind]:<11} missing={missing_totals[kind]:<3} "
              f"extra={extra_totals[kind]:<3} differs={differing_totals[kind]}")


if __name__ == "__main__":
    main()