"""Render the schema alignment inventory from the two rendered inventories."""

def load(path):
    tables, columns, indexes, constraints = set(), set(), set(), set()
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if not line or "|" not in line:
            continue
        parts = line.split("|")
        kind = parts[0]
        if kind == "TABLE":
            tables.add(parts[1])
        elif kind == "COLUMN":
            columns.add(line)
        elif kind == "INDEX":
            indexes.add("|".join(parts[:4]))
        elif kind == "CONSTRAINT":
            constraints.add("|".join(parts[:4]))
    return tables, columns, indexes, constraints

up_t, up_c, up_i, up_k = load("/tmp/up.schema")
wy_t, wy_c, wy_i, wy_k = load("/tmp/wy.schema")

missing_t = sorted(up_t - wy_t)
extra_t = sorted(wy_t - up_t)
missing_c = sorted(up_c - wy_c)
extra_c = sorted(wy_c - up_c)
missing_i = sorted(up_i - wy_i)
extra_i = sorted(wy_i - up_i)
missing_k = sorted(up_k - wy_k)
extra_k = sorted(wy_k - up_k)

def section(title, rows, fmt):
    out = [f"### {title} ({len(rows)})", ""]
    if not rows:
        out.append("None.")
        out.append("")
        return out
    out.append("```")
    for row in rows:
        out.append(fmt(row))
    out.append("```")
    out.append("")
    return out

lines = [
    "# Schema alignment inventory",
    "",
    "Generated by `scripts/schema_inventory.py` from two live schemas rendered by",
    "`scripts/schema_diff.sql`: the upstream database (`hindsight`, built by",
    "Alembic) and a freshly migrated wenyuan schema.",
    "",
    "**This is the work order.** It is derived from `information_schema` and",
    "`pg_catalog`, never from reading migrations or documentation, because the",
    "question is what a query sees at run time.",
    "",
    "## Totals",
    "",
    "| | upstream | wenyuan | missing | extra |",
    "|---|---|---|---|---|",
    f"| tables | {len(up_t)} | {len(wy_t)} | {len(missing_t)} | {len(extra_t)} |",
    f"| columns | {len(up_c)} | {len(wy_c)} | {len(missing_c)} | {len(extra_c)} |",
    f"| indexes | {len(up_i)} | {len(wy_i)} | {len(missing_i)} | {len(extra_i)} |",
    f"| constraints | {len(up_k)} | {len(wy_k)} | {len(missing_k)} | {len(extra_k)} |",
    "",
    "A missing entry breaks a query or loses a guarantee. An extra entry is",
    "additive and harmless unless it collides with an upstream name.",
    "",
]
lines += section("Tables upstream has and wenyuan lacks", missing_t, lambda r: r)
lines += section("Tables wenyuan has and upstream lacks", extra_t, lambda r: r)
lines += section("Columns upstream has and wenyuan lacks", missing_c,
                 lambda r: "|".join(r.split("|")[1:]))
lines += section("Columns wenyuan has and upstream lacks", extra_c,
                 lambda r: "|".join(r.split("|")[1:]))
lines += section("Indexes upstream has and wenyuan lacks", missing_i,
                 lambda r: "|".join(r.split("|")[1:]))
lines += section("Indexes wenyuan has and upstream lacks", extra_i,
                 lambda r: "|".join(r.split("|")[1:]))
lines += section("Constraints upstream has and wenyuan lacks", missing_k,
                 lambda r: "|".join(r.split("|")[1:]))
lines += section("Constraints wenyuan has and upstream lacks", extra_k,
                 lambda r: "|".join(r.split("|")[1:]))

open("docs/SCHEMA-ALIGNMENT.md", "w", encoding="utf-8").write("\n".join(lines))
print("wrote docs/SCHEMA-ALIGNMENT.md")
print("missing:", len(missing_t), len(missing_c), len(missing_i), len(missing_k))
print("extra:  ", len(extra_t), len(extra_c), len(extra_i), len(extra_k))
