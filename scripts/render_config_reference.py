#!/usr/bin/env python3
"""Render the configuration reference artifacts from the resolver key inventory.

Input is the JSON the TestDumpKeyInventory probe writes (default
/tmp/wenyuan_inventory.json). Three artifacts are rewritten, all idempotent:

  - etc/wenyuan.yaml       the shipped YAML template, full key coverage
  - .env.example           the same surface in dotenv form
  - docs/CONFIGURATION.md  the full key table: defaults, refusals, reasons

Regenerate with:

    go test ./internal/config -run TestDumpKeyInventory -count=1
    python3 scripts/render_config_reference.py

A key is spelled in the files as its environment name lowercased without the
HINDSIGHT_API_ prefix. Every template line is commented out, so copying either
template changes nothing until a line is uncommented.
"""

import json
import pathlib
import re
import sys

PREFIX = "HINDSIGHT_API_"
DEFAULT_INVENTORY = "/tmp/wenyuan_inventory.json"
ROOT = pathlib.Path(__file__).resolve().parent.parent

YAML_HEADER = """\
# Example configuration file for the wenyuan server, its worker and bankctl.
#
# The processes read etc/wenyuan.yaml from the working directory (inside the
# container image that is /etc/wenyuan.yaml); that file carries a deployment's
# real values and is deliberately not checked in. Copy this example there and
# uncomment what the deployment needs. Point the process elsewhere with
# HINDSIGHT_API_CONFIG_FILE=/path/to/file.yaml, which must exist.
#
# Precedence, highest first:
#
#   1. command-line flags
#   2. the .env file (a discovered .env is authoritative over the environment,
#      the reference's own entrypoint rule)
#   3. the rest of the process environment
#   4. this file
#   5. the built-in defaults
#
# A key is the environment variable's name without the HINDSIGHT_API_ prefix:
# HINDSIGHT_API_PORT is `port` here. A first word that carries several settings
# becomes a group — worker: {max_retries: 3} answers worker_max_retries — while
# a single-setting name stays flat (access_log). Either spelling answers the
# same key; if both appear with different values, startup names the
# disagreement. A list value is refused: an environment value cannot carry
# one, so a setting whose value is a mapping or a list must be spelled as a
# quoted JSON string.
#
# Quote a value that must stay a string: `api_key: "00123"` keeps its leading
# zeroes, while the bare 00123 would be read as the number 123. A key the server
# does not read is ignored, exactly as an unknown environment variable is.
#
# Every line below is commented out, so this example changes nothing as
# shipped. docs/CONFIGURATION.md is the generated reference: every key with
# its reference default, and why a refused one is refused.

"""

ENV_HEADER = """\
# wenyuan environment variables (server, worker and bankctl).
#
# Copy this file to .env in the working directory and uncomment the lines you
# want; a discovered .env is authoritative over the already-exported
# environment, the reference's own entrypoint rule. Every line below is
# commented out, so copying the file changes nothing until you edit it.
#
# The same keys can be set in the YAML configuration file etc/wenyuan.yaml
# (spelled lowercased without the HINDSIGHT_API_ prefix, behind the process
# environment). docs/CONFIGURATION.md is the generated reference: every key
# with its reference default, and why a refused one is refused.

"""

DOC_HEADER = """\
<!-- Generated by scripts/render_config_reference.py from the resolver key
     inventory (TestDumpKeyInventory). Do not edit by hand; regenerate with:

         go test ./internal/config -run TestDumpKeyInventory -count=1
         python3 scripts/render_config_reference.py
-->

# Configuration reference

Every environment variable the resolver reads, the YAML configuration file
spelling of the same key (lowercased, without the `HINDSIGHT_API_` prefix),
the reference's recorded default, and the key's status in this build. The same
surface ships as `etc/example.wenyuan.yaml` and `.env.example`, both fully
commented out.

Precedence, highest first: command-line flags, the `.env` file (a discovered
`.env` is authoritative over the environment, the reference's own entrypoint
rule), the rest of the process environment, `etc/wenyuan.yaml`, the built-in
defaults.

Status words:

- **resolved** — the build acts on the key.
- **value-dependent** — honoured for some values and refused for the rest; the
  note names the boundary.
- **refused** — the build rejects a non-blank value at startup, naming the key.
- **delegated** — another package resolves the key; the file layer still
  answers it.

"""


def file_key(env_name):
    return env_name[len(PREFIX):].lower()


def yaml_scalar(value):
    value = value.replace('"', '\\"')
    return f'"{value}"'


def runtime_status(row):
    if row.get("delegated"):
        return "delegated", f"resolved by {row['delegated']}"
    if row.get("value_dependent"):
        return "value-dependent", row.get("reason", "")
    if row["resolved"]:
        return "resolved", row.get("divergent", "")
    return "refused", row.get("reason", "")


def template_note(row):
    """One-line comment for the templates. A value-dependent key honours the
    value shown, so the note must not read as if the line were inert."""
    if row.get("delegated"):
        return f"resolved by {row['delegated']}"
    if row.get("value_dependent"):
        return f"value-dependent, honoured as shown: {row.get('reason', '')}"
    if row["resolved"]:
        return row.get("divergent", "")
    return f"refused by this build: {row.get('reason', '')}"


def render_templates(inv):
    """Return (yaml_body, env_body) covering every key. The YAML body renders
    the traditional nested form: a first word that carries more than one
    setting becomes a group (worker: {max_retries: ...} answers
    worker_max_retries), a single-setting name stays flat (access_log), and
    the loader flattens either spelling back to the flat key it asks for. The
    dotenv body stays flat: a dotenv value cannot nest."""
    env_lines = []
    counts = {}
    for source in (
        (row["key"] for row in inv["reference_default"]),
        (key for family in sorted(inv["provider_families"]) for key in
         inv["provider_families"][family]["resolved"] + inv["provider_families"][family]["refused"]),
        (key for key in list(inv["consolidation"]) + list(inv["scopes"]) + list(inv["false_defaults"])),
    ):
        for env_name in source:
            first = file_key(env_name).partition("_")[0]
            counts[first] = counts.get(first, 0) + 1

    tree = {}
    planted = 0

    def plant(flat_key, value, note):
        # A first word groups its keys only when there are several: one
        # setting stays flat (access_log), several nest (worker: {max_retries}).
        # Nesting deeper than the first word would make a leaf key
        # (mcp_enabled) and a deeper path (mcp_enabled_tools) unrepresentable
        # in one YAML document; sibling leaves never collide.
        first, _, rest = flat_key.partition("_")
        if counts.get(first, 0) < 2 or not rest:
            if first != flat_key and isinstance(tree.get(first), dict):
                raise SystemExit(f"renderer: flat key {flat_key!r} collides with the nested subtree {first!r}")
            tree[flat_key] = (value, note)
            return
        node = tree.get(first)
        if node is None:
            node = tree[first] = {}
        elif isinstance(node, tuple):
            raise SystemExit(f"renderer: flat key {flat_key!r} collides with the leaf {first!r}")
        node[rest] = (value, note)

    def emit(env_name, default, note):
        nonlocal planted
        flat_key = file_key(env_name)
        plant(flat_key, default, note)
        planted += 1
        env_lines.append(f"# {env_name}={default}{('  # ' + note) if note else ''}")

    for row in inv["reference_default"]:
        emit(row["key"], row["upstream_default"], template_note(row))

    seen = {row["key"] for row in inv["reference_default"]}
    for family in sorted(inv["provider_families"]):
        keys = inv["provider_families"][family]
        for key in keys["resolved"] + keys["refused"]:
            if key in seen:
                continue
            seen.add(key)
            note = "" if key in keys["resolved"] else "refused by this build"
            emit(key, "", note)

    for key in list(inv["consolidation"]) + list(inv["scopes"]) + sorted(inv["false_defaults"]):
        if key not in seen:
            seen.add(key)
            emit(key, "", "")

    yaml_lines = []

    def render(node, depth):
        pad = "  " * depth
        for name, child in node.items():
            if isinstance(child, dict):
                yaml_lines.append(f"{pad}# {name}:")
                render(child, depth + 1)
            else:
                value, note = child
                suffix = f"  # {note}" if note else ""
                yaml_lines.append(f"{pad}# {name}: {yaml_scalar(value)}{suffix}")

    render(tree, 0)
    return "\n".join(yaml_lines) + "\n", "\n".join(env_lines) + "\n", planted


def render_docs(inv):
    lines = [DOC_HEADER]
    lines.append("## Runtime keys\n")
    lines.append("| Environment variable | File key | Reference default | Status | Notes |")
    lines.append("| --- | --- | --- | --- | --- |")
    for row in inv["reference_default"]:
        status, note = runtime_status(row)
        note = note.replace("|", "\\|")
        lines.append(
            f"| `{row['key']}` | `{file_key(row['key'])}` | `{row['upstream_default']}` "
            f"| {status} | {note} |"
        )
    seen = {row["key"] for row in inv["reference_default"]}
    for family in sorted(inv["provider_families"]):
        keys = inv["provider_families"][family]
        lines.append(f"\n## Provider family: `{family}`\n")
        lines.append("| Environment variable | File key | Status |")
        lines.append("| --- | --- | --- |")
        for key in keys["resolved"] + keys["refused"]:
            if key in seen:
                continue
            seen.add(key)
            status = "resolved" if key in keys["resolved"] else "refused"
            lines.append(f"| `{key}` | `{file_key(key)}` | {status} |")
    extra = []
    for key in list(inv["consolidation"]) + list(inv["scopes"]) + sorted(inv["false_defaults"]):
        if key not in seen:
            seen.add(key)
            extra.append(key)
    if extra:
        lines.append("\n## Additional keys\n")
        lines.append("| Environment variable | File key |")
        lines.append("| --- | --- |")
        for key in extra:
            lines.append(f"| `{key}` | `{file_key(key)}` |")
    return "\n".join(lines) + "\n"


def main():
    inventory = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(DEFAULT_INVENTORY)
    inv = json.loads(inventory.read_text())
    yaml_body, env_body, keys = render_templates(inv)
    (ROOT / "etc" / "example.wenyuan.yaml").write_text(YAML_HEADER + yaml_body)
    (ROOT / ".env.example").write_text(ENV_HEADER + env_body)
    (ROOT / "docs" / "CONFIGURATION.md").write_text(render_docs(inv))
    print(f"wrote etc/example.wenyuan.yaml, .env.example and docs/CONFIGURATION.md ({keys} keys)")


if __name__ == "__main__":
    main()
